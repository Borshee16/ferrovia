function toRad(value) {
  return (value * Math.PI) / 180;
}

function projectPointToSegmentMeters(gps, a, b) {
  const lat0 = toRad((a.lat + b.lat + gps.lat) / 3);
  const mx = 111320 * Math.cos(lat0);
  const my = 110540;

  const ax = a.lon * mx;
  const ay = a.lat * my;
  const bx = b.lon * mx;
  const by = b.lat * my;
  const px = gps.lon * mx;
  const py = gps.lat * my;

  const dx = bx - ax;
  const dy = by - ay;
  const len2 = dx * dx + dy * dy;

  if (len2 === 0) {
    const dist = Math.hypot(px - ax, py - ay);
    return { t: 0, distanceMeters: dist, lat: a.lat, lon: a.lon };
  }

  const tRaw = ((px - ax) * dx + (py - ay) * dy) / len2;
  const t = Math.max(0, Math.min(1, tRaw));

  const cx = ax + t * dx;
  const cy = ay + t * dy;
  const distanceMeters = Math.hypot(px - cx, py - cy);

  return {
    t,
    distanceMeters,
    lat: a.lat + (b.lat - a.lat) * t,
    lon: a.lon + (b.lon - a.lon) * t,
  };
}

export function trovaPosizioneSuMasterDaGps(location) {
  if (
    !location ||
    !Number.isFinite(location.latitude) ||
    !Number.isFinite(location.longitude)
  ) {
    return null;
  }

  const gps = { lat: location.latitude, lon: location.longitude };
  let best = null;

  for (let i = 0; i < MASTER_BARI_TARANTO_POINTS.length - 1; i += 1) {
    const a = MASTER_BARI_TARANTO_POINTS[i];
    const b = MASTER_BARI_TARANTO_POINTS[i + 1];
    const projected = projectPointToSegmentMeters(gps, a, b);
    const distanzaMasterMetri = a.d + (b.d - a.d) * projected.t;

    if (!best || projected.distanceMeters < best.distanzaDaLineaMetri) {
      best = {
        distanzaMasterMetri,
        distanzaDaLineaMetri: projected.distanceMeters,
        puntoMaster: {
          latitude: projected.lat,
          longitude: projected.lon,
        },
        segmentoIndex: i,
      };
    }
  }

  if (!best) return null;

  return {
    ...best,
    qualitaAggancio:
      best.distanzaDaLineaMetri <= 40
        ? "alta"
        : best.distanzaDaLineaMetri <= 120
        ? "media"
        : "bassa",
  };
}

export function getMasterBariTarantoLengthMeters() {
  const last = MASTER_BARI_TARANTO_POINTS[MASTER_BARI_TARANTO_POINTS.length - 1];
  return last ? last.d : 0;
}